// Deploys FreelanceEscrow to the local Hardhat node and sets up the same demo community
// as the web app. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const Role = { Client: 1, Freelancer: 2 };

async function main() {
  const signers = await hre.ethers.getSigners();
  const [council] = signers;

  const escrow = await hre.ethers.deployContract("FreelanceEscrow", [], council);
  await escrow.waitForDeployment();
  const address = await escrow.getAddress();
  console.log(`FreelanceEscrow deployed to ${address} by the GigSafe Council ${council.address}`);

  // The Council appoints the arbiter panel (permissioned) ...
  const panel = [
    [signers[1], "Arbiter Meera"],
    [signers[2], "Arbiter Daniel"],
    [signers[3], "Arbiter Kofi"],
  ];
  await (await escrow.setArbiters(panel.map(([s]) => s.address), panel.map(([, n]) => n))).wait();
  for (const [signer, name] of panel) console.log(`  arbiter     ${name.padEnd(20)} ${signer.address}`);

  // ... clients and freelancers register themselves (permissionless). Account 8 (copy_sam)
  // is left unregistered so the demo can show self-registration in the web app.
  const users = [
    [signers[4], Role.Client, "Bluefin Startups"],
    [signers[5], Role.Client, "Corner Bakery Co."],
    [signers[6], Role.Freelancer, "pixel_priya"],
    [signers[7], Role.Freelancer, "dev_arjun"],
  ];
  for (const [signer, role, name] of users) {
    await (await escrow.connect(signer).registerUser(role, name)).wait();
    console.log(`  ${role === Role.Client ? "client    " : "freelancer"}  ${name.padEnd(20)} ${signer.address}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
